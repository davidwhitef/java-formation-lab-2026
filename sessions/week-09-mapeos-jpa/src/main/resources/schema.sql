-- Customer: entidad raíz, independiente. Address se incrusta (@Embeddable).
CREATE TABLE IF NOT EXISTS customers (
                                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    street      VARCHAR(255),
    city        VARCHAR(255),
    postal_code VARCHAR(255),
    country     VARCHAR(255),
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT uk_customers_email UNIQUE (email)
    );

-- Product: catálogo independiente. version soporta @Version (optimistic locking).
CREATE TABLE IF NOT EXISTS products (
                                        id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        name    VARCHAR(255) NOT NULL,
    price   NUMERIC(19,2) NOT NULL,
    stock   INTEGER NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
    );

-- Order: customer_id obligatorio, SIN ON DELETE CASCADE hacia customers
-- (Order->Customer no tiene cascade en JPA: borrar un cliente con pedidos
-- debe ser una decisión de negocio explícita, no un efecto colateral del DDL).
CREATE TABLE IF NOT EXISTS orders (
                                      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      status      VARCHAR(20) NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    customer_id BIGINT NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
    REFERENCES customers (id),
    CONSTRAINT chk_orders_status CHECK (status IN ('PENDING','CONFIRMED','SHIPPED'))
    );

-- OrderItem: order_id obligatorio + ON DELETE CASCADE, respaldo físico en BD
-- de orphanRemoval=true (si algo borra un Order fuera del ORM, la BD impide
-- que quede un OrderItem huérfano). product_id obligatorio, SIN cascade
-- (el producto del catálogo nunca se borra en cascada al borrar un pedido).
CREATE TABLE IF NOT EXISTS order_items (
                                           id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           quantity   INTEGER NOT NULL,
                                           unit_price NUMERIC(19,2) NOT NULL,
    order_id   BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
    REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id)
    REFERENCES products (id),
    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0)
    );

CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders (customer_id);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON order_items (product_id);